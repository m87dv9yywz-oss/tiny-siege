import { chromium, webkit } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
const url = process.argv[2];
const expected = '6dd8ae6b6bd26b8e46f7d1ba8a0aa0477aeba82d';
const metadata = await fetch(new URL('preview.json', url)).then(r => { assert.equal(r.status, 200); return r.json(); });
assert.equal(metadata.commit, expected);
assert.equal(metadata.cloud, false);
assert.equal(metadata.base, '/');
mkdirSync('test-results/public-preview', { recursive: true });
const reports=[];
for (const [name, engine] of [['chromium', chromium], ['webkit', webkit]]) {
  if (process.env.LOCAL_PREVIEW && name === 'webkit') continue;
  const browser = await engine.launch(process.env.LOCAL_PREVIEW ? { executablePath:'/usr/bin/chromium', args:['--no-sandbox'] } : {});
  try {
    const context=await browser.newContext({viewport:{width:844,height:390},hasTouch:true,isMobile:true});
    await context.addInitScript(() => localStorage.setItem('tiny-siege-profiles-v3','PRODUCTION_SENTINEL_DO_NOT_TOUCH'));
    const page=await context.newPage();
    page.setDefaultTimeout(60000);
    const external=[],errors=[],bad=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('request',r=>{ if(new URL(r.url()).origin!==new URL(url).origin && /^https?:/.test(r.url())) external.push(r.url()); });
    page.on('response',r=>{if(r.status()>=400)bad.push([r.status(),r.url()]);});
    assert.equal((await page.goto(url)).status(),200);
    await page.waitForFunction(()=>document.querySelector('#game')?.getAttribute('aria-busy')==='false' && document.querySelector('#play'));
    assert.match(await page.title(), /V5 Preview/);
    await page.locator('#parent-cloud').tap();
    await page.waitForFunction(()=>document.querySelector('#modal-title')?.textContent==='Preview saves stay here');
    assert.equal(await page.locator('#google-sign-in').count(),0);
    await page.screenshot({path:`test-results/public-preview/${name}-isolated-saves.png`});
    await page.locator('#back').tap();
    await page.locator('#new-profile').tap();
    await page.locator('#nickname').fill('Isolated phone tester');
    await page.locator('#profile-form button').tap();
    await page.locator('#play').tap();
    await page.locator('[data-tower="archer"]').tap();
    let b=await page.locator('canvas').boundingBox();
    assert.ok(b.width>=530 && Math.abs(b.width/b.height-1.5)<0.01);
    await page.touchscreen.tap(b.x+b.width*145/960,b.y+b.height*105/640);
    await page.waitForFunction(()=>document.querySelector('#gold').textContent==='225');
    await page.locator('[data-upgrade="0"]').tap();
    await page.waitForFunction(()=>document.querySelector('#gold').textContent==='125');
    await page.locator('#speed').tap();
    await page.locator('#start-wave').tap();
    await page.waitForFunction(()=>Number(document.querySelector('#gold').textContent)>125);
    assert.equal(await page.locator('#selection-panel').isVisible(),true);
    await page.screenshot({path:`test-results/public-preview/${name}-landscape-battle.png`});
    await page.locator('#pause').tap();
    await page.setViewportSize({width:390,height:844});
    await page.waitForTimeout(1000);
    b=await page.locator('canvas').boundingBox();
    assert.ok(Math.abs(b.width/b.height-1.5)<0.01);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.screenshot({path:`test-results/public-preview/${name}-portrait-battle.png`});
    await page.locator('#close-panel').tap();
    await page.locator('#pause').tap();
    await page.waitForFunction(()=>document.querySelector('#start-wave').textContent.includes('START WAVE 2'),null,{timeout:90000});
    const beforePlacement=Number(await page.locator('#gold').textContent());
    await page.locator('[data-tower="archer"]').tap();
    b=await page.locator('canvas').boundingBox();
    await page.touchscreen.tap(b.x+b.width*745/960,b.y+b.height*330/640);
    await page.waitForFunction(expected=>Number(document.querySelector('#gold').textContent)===expected,beforePlacement-75);
    await page.locator('#leave-run').tap();
    await page.locator('#confirm-leave').tap();
    await page.locator('[data-map="emerald"]').tap();
    await page.waitForLoadState('networkidle');
    await page.screenshot({path:`test-results/public-preview/${name}-preparation.png`});
    await page.locator('#begin-adventure').tap();
    await page.waitForLoadState('networkidle');
    await page.waitForTimeout(200);
    for(const [width,height] of [[844,330],[667,320],[390,730]]) {
      await page.setViewportSize({width,height});
      await page.waitForTimeout(300);
      const outside=await page.locator('.tower-card').evaluateAll(cards=>cards.flatMap(c=>{
        const b=c.getBoundingClientRect();const icon=c.querySelector('.tower-icon img').getBoundingClientRect(),label=c.querySelector('.tower-name b').getBoundingClientRect();if(icon.bottom>label.top+1)return[c.dataset.tower,'icon overlaps label'];return ['.tower-icon img','.tower-cost','.tower-name b',...(c.classList.contains('locked')?['.tower-lock']:[])].flatMap(selector=>{const p=c.querySelector(selector).getBoundingClientRect();return p.left<b.left-1||p.right>b.right+1||p.top<b.top-1||p.bottom>b.bottom+1?[c.dataset.tower,selector]:[];});
      }));
      assert.deepEqual(outside,[]);
      await page.screenshot({path:`test-results/public-preview/${name}-hero-shop-${width}x${height}.png`});
    }
    await page.waitForTimeout(1500);
    const safety=await page.evaluate(()=>({keys:Object.keys(localStorage),original:localStorage.getItem('tiny-siege-profiles-v3'),csp:document.querySelector('meta[http-equiv="Content-Security-Policy"]').content,dev:typeof window.__tinySiege}));
    assert.equal(safety.original,'PRODUCTION_SENTINEL_DO_NOT_TOUCH');
    assert.equal(safety.dev,'undefined');
    assert.ok(safety.keys.includes('tiny-siege-v5-pr17-preview-e121297'));
    assert.match(safety.csp,/connect-src 'self'/);
    assert.deepEqual(external,[]);
    assert.deepEqual(errors,[]);
    assert.deepEqual(bad,[]);
    reports.push({engine:name,metadata,canvas:b,safety,external,errors,bad});
    console.log(`${name}: public HTTPS, isolated saves, no Firebase, real placement/upgrade/combat/pause/rotation passed`);
  } finally {await browser.close();}
}
writeFileSync('test-results/public-preview/isolation.json',JSON.stringify(reports,null,2));
